// Copies the Hugeicons (solid, rounded) used by the app into
// src/components/icons.tsx, recolored to currentColor.
//
//   pnpm gen:icons [path-to-hugeicons/icons]
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SOURCE = process.argv[2] ?? '/Users/dhruvdeora/Desktop/Coding/hugeicons-repo-dump/icons'
const STYLE = 'solid-rounded'

// app name → hugeicons file name
const ICONS: Record<string, string> = {
  sparkles: 'sparkles',
  fire: 'fire',
  keyboard: 'keyboard',
  toggle: 'toggle-on',
  move: 'move',
  cursor: 'cursor-text',
  footprints: 'running-shoes',
  arrows: 'arrow-up-down',
  crosshair: 'target-02',
  search: 'search-01',
  eraser: 'eraser',
  undo: 'undo-02',
  zap: 'flash',
  clipboard: 'copy-01',
  wand: 'magic-wand-01',
  brackets: 'code',
  highlighter: 'highlighter',
  star: 'star',
  lock: 'square-lock-02',
  check: 'tick-02',
  'chevron-left': 'arrow-left-01',
  'arrow-right': 'arrow-right-02',
  play: 'play',
  restart: 'reload',
  bulb: 'bulb',
  close: 'cancel-01',
  gem: 'diamond',
  trophy: 'champion',
  timer: 'timer-02',
  grid: 'dashboard-square-01',
  gamepad: 'game-controller-03',
  book: 'book-open-01',
  target: 'target-01',
  eye: 'view',
  skip: 'next',
  menu: 'menu-01',
}

const body = Object.entries(ICONS)
  .map(([name, file]) => {
    const svg = readFileSync(join(SOURCE, `${file}-${STYLE}.svg`), 'utf8')
    const inner = svg
      .replace(/^[\s\S]*?<svg[^>]*>/, '')
      .replace(/<\/svg>[\s\S]*$/, '')
      .replace(/#141B34/gi, 'currentColor')
      .replace(/\s*\n\s*/g, '')
    return `  '${name}': ${JSON.stringify(inner)},`
  })
  .join('\n')

const out = `// Generated by scripts/gen-icons.ts from Hugeicons (${STYLE}). Do not edit by hand.
import type { SVGProps } from 'react'

const paths = {
${body}
} as const

export type IconName = keyof typeof paths

export function Icon({ name, size = 20, ...props }: { name: IconName; size?: number } & Omit<SVGProps<SVGSVGElement>, 'name'>) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden
      {...props}
      dangerouslySetInnerHTML={{ __html: paths[name] }}
    />
  )
}
`
writeFileSync(new URL('../src/components/icons.tsx', import.meta.url), out)
console.log(`Wrote ${Object.keys(ICONS).length} icons`)
